/// Zero means unreported. Other tags record explicit source facts.
/// cbindgen:rename-all=QualifiedScreamingSnakeCase
#[repr(C)]
#[derive(Clone, Copy)]
pub enum GtdSolutionState {
    /// Estimate without measured GNSS contribution.
    EstimatedOnly = 3,
    /// Solution with measured GNSS contribution.
    Fix = 1,
    /// Source-reported navigation loss.
    NoFix = 2,
    /// Explicit uncertainty that blocks fallback state inference.
    Unknown = 4,
    /// No source state observation. Fallback evidence remains eligible.
    Unreported = 0,
}

/// Zero means unreported. Other tags record explicit source facts.
/// cbindgen:rename-all=QualifiedScreamingSnakeCase
#[repr(C)]
#[derive(Clone, Copy)]
pub enum GtdSolutionMethod {
    /// GNSS positioning without differential corrections.
    Autonomous = 1,
    /// Position estimation from motion measurements.
    DeadReckoning = 5,
    /// GNSS positioning with differential corrections.
    Differential = 2,
    /// Combined positioning with measured GNSS contribution.
    Hybrid = 6,
    /// Reported method outside this vocabulary.
    Other = 7,
    /// Real-time kinematic positioning with fixed ambiguities.
    RtkFixed = 4,
    /// Real-time kinematic positioning with float ambiguities.
    RtkFloat = 3,
    /// No reported positioning method.
    Unreported = 0,
}

/// Zero means unreported. Other tags record explicit source facts.
/// cbindgen:rename-all=QualifiedScreamingSnakeCase
#[repr(C)]
#[derive(Clone, Copy)]
pub enum GtdSolutionDimension {
    /// Horizontal and vertical solution.
    ThreeD = 2,
    /// Horizontal solution.
    TwoD = 1,
    /// No reported solution dimension.
    Unreported = 0,
}

/// Zero means unreported. Other tags record explicit source facts.
/// cbindgen:rename-all=QualifiedScreamingSnakeCase
#[repr(C)]
#[derive(Clone, Copy)]
pub enum GtdPositionProvenance {
    /// Coordinates generated by the SDK.
    SdkSynthesized = 2,
    /// Caller-supplied coordinates, including estimates and measurements.
    SourceProvided = 1,
    /// Unreported coordinate origin, including legacy files.
    Unreported = 0,
}

/// `present == 0` means absent. Every `uint32_t` value is valid when present.
#[repr(C)]
#[derive(Clone, Copy)]
pub struct GtdOptU32 {
    /// Reported count when present, including zero.
    pub value: u32,
    /// Zero for absent, nonzero for present.
    pub present: u8,
}

impl GtdOptU32 {
    pub(crate) fn to_opt(self) -> Option<u32> {
        (self.present != 0).then_some(self.value)
    }
}

impl From<Option<u32>> for GtdOptU32 {
    fn from(value: Option<u32>) -> Self {
        Self {
            value: value.unwrap_or_default(),
            present: u8::from(value.is_some()),
        }
    }
}

/// Raw tags use the corresponding `GtdSolution*` and `GtdPositionProvenance` constants.
/// DOP is dimensionless. Present NaN optional numbers decode as absent after serialization.
#[repr(C)]
#[derive(Clone, Copy)]
pub struct GtdNavFixV2 {
    /// Receiver timestamp, or `gtd_ts_none()` when unreported.
    pub gps_time: GtdTimestamp,
    /// Host timestamp, or `gtd_ts_none()` when unreported.
    pub sys_time: GtdTimestamp,
    /// WGS-84 latitude in degrees.
    pub lat_deg: f64,
    /// WGS-84 longitude in degrees.
    pub lon_deg: f64,
    /// Compass heading in degrees, independent of navigation state.
    pub heading_deg: GtdOptF64,
    /// Ground speed in metres per second.
    pub speed_mps: GtdOptF64,
    /// Reported horizontal accuracy in metres, separate from DOP.
    pub eph_m: GtdOptF64,
    /// A `GtdSolutionState` tag. Unreported and explicit Unknown are distinct.
    pub state: u32,
    /// A `GtdSolutionMethod` tag. Method does not override state.
    pub method: u32,
    /// A `GtdSolutionDimension` tag. Dimension does not override state.
    pub dimension: u32,
    /// A `GtdPositionProvenance` tag. Source coordinates need not be measured.
    pub position_provenance: u32,
    /// Optional source-reported global used aggregate, independent of identity lists.
    pub used_count: GtdOptU32,
    /// Horizontal dilution of precision.
    pub hdop: GtdOptF64,
    /// Vertical dilution of precision.
    pub vdop: GtdOptF64,
    /// Position dilution of precision.
    pub pdop: GtdOptF64,
}

impl GtdNavFixV2 {
    pub(crate) fn to_sdk(self) -> Result<NavFix, GtdStatus> {
        let mut fix = NavFix::builder()
            .time(
                TimestampArguments {
                    gps_time: self.gps_time,
                    sys_time: self.sys_time,
                }
                .into_nav_fix_time("a fix")?,
            )
            .lat(Angle::degrees(self.lat_deg))
            .lon(Angle::degrees(self.lon_deg))
            .maybe_heading(self.heading_deg.to_opt().map(Angle::degrees))
            .maybe_speed(self.speed_mps.to_opt().map(Velocity::meter_per_second))
            .maybe_eph_m(self.eph_m.to_opt())
            .build();
        fix.state = if self.state == 0 {
            None
        } else {
            Some(
                u8::try_from(self.state)
                    .ok()
                    .and_then(SolutionState::from_repr)
                    .ok_or_else(|| invalid_field("state"))?,
            )
        };
        fix.method = if self.method == 0 {
            None
        } else {
            Some(
                u8::try_from(self.method)
                    .ok()
                    .and_then(SolutionMethod::from_repr)
                    .ok_or_else(|| invalid_field("method"))?,
            )
        };
        fix.dimension = if self.dimension == 0 {
            None
        } else {
            Some(
                u8::try_from(self.dimension)
                    .ok()
                    .and_then(SolutionDimension::from_repr)
                    .ok_or_else(|| invalid_field("dimension"))?,
            )
        };
        fix.position_provenance = if self.position_provenance == 0 {
            None
        } else {
            Some(
                u8::try_from(self.position_provenance)
                    .ok()
                    .and_then(PositionProvenance::from_repr)
                    .ok_or_else(|| invalid_field("position_provenance"))?,
            )
        };
        fix.used_count = self.used_count.to_opt();
        fix.hdop = self.hdop.to_opt();
        fix.vdop = self.vdop.to_opt();
        fix.pdop = self.pdop.to_opt();
        Ok(fix)
    }
}

impl From<NavFix> for GtdNavFixV2 {
    fn from(fix: NavFix) -> Self {
        Self {
            gps_time: fix
                .gps_time()
                .map_or(timestamp::gtd_ts_none(), timestamp::ts_from_datetime),
            sys_time: fix
                .sys_time()
                .map_or(timestamp::gtd_ts_none(), timestamp::ts_from_datetime),
            lat_deg: fix.lat.as_degrees(),
            lon_deg: fix.lon.as_degrees(),
            heading_deg: fix.heading.map(Angle::as_degrees).into(),
            speed_mps: fix.speed.map(Velocity::as_meters_per_second).into(),
            eph_m: fix.eph_m.into(),
            state: fix.state.map_or(0, |value| u32::from(value as u8)),
            method: fix.method.map_or(0, |value| u32::from(value as u8)),
            dimension: fix.dimension.map_or(0, |value| u32::from(value as u8)),
            position_provenance: fix
                .position_provenance
                .map_or(0, |value| u32::from(value as u8)),
            used_count: fix.used_count.into(),
            hdop: fix.hdop.into(),
            vdop: fix.vdop.into(),
            pdop: fix.pdop.into(),
        }
    }
}

pub(crate) struct TimestampArguments {
    pub(crate) gps_time: GtdTimestamp,
    pub(crate) sys_time: GtdTimestamp,
}

impl TimestampArguments {
    pub(crate) fn into_nav_fix_time(
        self,
        what_needs_a_timestamp: &str,
    ) -> Result<NavFixTime, GtdStatus> {
        let recorded = RecordedFixTimestamps {
            gps: self.gps_time.to_optional_datetime("gps_time")?,
            sys: self.sys_time.to_optional_datetime("sys_time")?,
        };
        NavFixTime::from_recorded(recorded).ok_or_else(|| {
            error::set_last_error(format!(
                "gps_time and sys_time are both gtd_ts_none(): {what_needs_a_timestamp} needs one"
            ));
            GtdStatus::GTD_ERR_INVALID_ARGUMENT
        })
    }
}

pub(crate) fn invalid_field(field: impl Display) -> GtdStatus {
    error::set_last_error(format!("{field}: invalid value"));
    GtdStatus::GTD_ERR_INVALID_ARGUMENT
}

/// Initialize absent metadata with `GTD_POSITION_PROVENANCE_SOURCE_PROVIDED`.
/// Set at least one timestamp and the coordinates before ingestion.
#[unsafe(no_mangle)]
pub extern "C" fn gtd_nav_fix_v2_init() -> GtdNavFixV2 {
    let mut fix = GtdNavFixV2::from(
        NavFix::builder()
            .time(NavFixTime::Host(DateTime::UNIX_EPOCH))
            .lat(Angle::degrees(0.0))
            .lon(Angle::degrees(0.0))
            .build(),
    );
    fix.sys_time = timestamp::gtd_ts_none();
    fix
}

/// Initialize an explicit status with absent coordinates and coordinate origin.
/// Set at least one timestamp before ingestion, which validates the raw state tag.
#[unsafe(no_mangle)]
pub extern "C" fn gtd_nav_fix_v2_status_only_init(state: u32) -> GtdNavFixV2 {
    let mut fix = GtdNavFixV2::from(NavFix::status_only(
        NavFixTime::Host(DateTime::UNIX_EPOCH),
        SolutionState::Unknown,
    ));
    fix.sys_time = timestamp::gtd_ts_none();
    fix.state = state;
    fix
}
